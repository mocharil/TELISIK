import assert from 'node:assert/strict';
import { evaluateImpact, initialImpact, parseImpact } from '../src/investigation/impact-model';
import { changeServiceEvidence, confirmServiceTicket, dualOutcome, evaluateService, executeService, initialService, lockService, parseService, serviceCsv, serviceReport, serviceTickets, signService, verifiedTicket } from '../src/investigation/service-model';

const example = initialService(), r = evaluateService(example);
assert.equal(r.tickets.length, 40);
assert.equal(new Set(r.tickets.map(t => t.id)).size, 40);
assert.equal(r.response.total, 20);
assert.equal(r.response.before, 2);
assert.equal(r.response.beforeRate, 10);
assert.equal(r.response.verified, 14);
assert.equal(r.response.verifiedRate, 70);
assert.equal(r.response.closed, 18);
assert.equal(r.response.closedRate, 90);
assert.equal(r.response.reopened, 2);
assert.equal(r.response.reopenedRate, 10);
assert.equal(r.comparison.verified, 6);
assert.equal(r.comparison.verifiedRate, 30);
assert.equal(r.change, 60);
assert.equal(r.comparisonChange, 20);
assert.equal(r.adjusted, 40);
assert.equal(r.targetMet, true);
assert.equal(evaluateService({ ...example, maxReopened: 5 }).targetMet, false, 'Reopening guardrail can fail despite sufficient verified answers');
const low = evaluateService({ ...example, mode: 'closed-only' });
assert.equal(low.response.closedRate, 90);
assert.equal(low.response.verifiedRate, 30, 'Administrative closure is not resident-confirmed resolution');
assert.equal(low.adjusted, 0);
assert.equal(low.targetMet, false);
const missing = evaluateService({ ...example, mode: 'missing' });
assert.equal(missing.comparison.total, 20, 'Missing follow-up must not shrink the fixed denominator');
assert.equal(missing.comparison.observed, 0);
assert.equal(missing.comparison.verifiedRate, null);
assert.equal(missing.adjusted, null);
assert.equal(missing.targetMet, true, 'Response target can be observed independently of a missing comparison');
assert.equal(missing.evidence, 'Insufficient comparison data');
for (const key of ['caseMix', 'spillover', 'logging', 'otherActions'] as const) {
  const x = evaluateService({ ...example, checks: { ...example.checks, [key]: false } });
  assert.equal(x.adjusted, null);
  assert.equal(x.targetMet, true);
}
const ticket = r.tickets.find(t => t.id === 'SC-R-017')!;
assert.equal(verifiedTicket(ticket), false);
assert.equal(verifiedTicket({ ...ticket, confirmationHour: 15.9, residentReference: 'CONFIRM' }), true);
assert.equal(verifiedTicket({ ...ticket, confirmationHour: 16.1, residentReference: 'CONFIRM' }), false, 'Confirmation after cutoff is not a timely resolution');
assert.equal(verifiedTicket({ ...ticket, confirmationHour: 1, residentReference: 'CONFIRM' }), false, 'Confirmation must follow the officer answer');
assert.equal(verifiedTicket({ ...ticket, confirmationHour: 15.9, residentReference: 'CONFIRM', reopened: true }), false);
assert.equal(verifiedTicket({ ...ticket, confirmationHour: 15.9, residentReference: 'CONFIRM', officerReference: null }), false);
const confirmation = { reviewer: 'AR', reference: 'DEMO-017', note: 'Resident confirms that the source-backed answer resolves the question.', recordedAt: '2026-10-23T04:00:00Z' };
let verified = confirmServiceTicket(example, 'SC-R-017', confirmation);
assert.equal(evaluateService(verified).response.verified, 15);
assert.equal(evaluateService(verified).response.verifiedRate, 75);
assert.equal(evaluateService(verified).response.total, 20);
assert.equal(confirmedCount(verified), 1);
assert.equal(confirmServiceTicket(verified, 'SC-R-017', confirmation), verified, 'Do not overwrite existing confirmation');
for (const id of ['SC-R-019', 'SC-R-015', 'SC-R-001', 'invented']) assert.equal(confirmServiceTicket(example, id, confirmation), example, 'Open, reopened, already-verified and unknown tickets are ineligible');
assert.equal(confirmServiceTicket({ ...example, mode: 'missing' }, 'SC-C-007', confirmation).confirmations['SC-C-007'], undefined);
assert.equal(confirmServiceTicket(example, 'SC-R-017', { ...confirmation, note: '' }), example);
const signoff = { reviewer: 'AR', decision: 'Continue monitoring', note: 'Verify the pending resident confirmations before extending the conclusion.', recordedAt: 'now' };
verified = signService(verified, signoff);
assert.ok(verified.signoff);
assert.equal(confirmServiceTicket(verified, 'SC-R-018', { ...confirmation, reference: 'DEMO-018' }).signoff, null);
assert.deepEqual(changeServiceEvidence(verified, { mode: 'closed-only' }, 'later').confirmations, {});
assert.equal(changeServiceEvidence(verified, { checks: { ...verified.checks, logging: false } }, 'later').signoff, null);
assert.equal(confirmedCount(changeServiceEvidence(verified, { checks: { ...verified.checks, logging: false } }, 'later')), 1);
let draft = initialService(false);
assert.equal(evaluateService(draft).targetMet, null);
assert.equal(evaluateService(draft).adjusted, null);
const execution = { officer: 'Demo officer', channel: 'Demo queue', proof: 'DEMO-C', wording: 'Answer and confirm resident complaints.', recordedAt: 'now' };
assert.equal(executeService(draft, execution), draft);
assert.equal(lockService({ ...draft, target: 101 }, 'now').lockedAt, null);
draft = lockService(draft, 'plan time');
assert.ok(draft.lockedAt);
assert.equal(executeService(draft, { ...execution, proof: '' }), draft);
draft = executeService(draft, execution);
assert.ok(draft.execution);
assert.equal(executeService(draft, execution), draft);
assert.equal(evaluateService(draft).adjusted, null, 'Service comparison checks are independently unresolved');
assert.deepEqual(parseService(JSON.stringify(verified)), verified);
for (const raw of [null, '{}', 'invalid', JSON.stringify({ ...draft, target: -1 }), JSON.stringify({ ...draft, checks: {} }), JSON.stringify({ ...draft, execution: {} }), JSON.stringify({ ...draft, lockedAt: null }), JSON.stringify({ ...draft, confirmations: { invented: confirmation } }), JSON.stringify({ ...draft, signoff: {} })]) assert.deepEqual(parseService(raw, false), initialService(false));
assert.equal(dualOutcome(true, true), 'Both outcome targets met');
assert.equal(dualOutcome(true, false), 'Partial outcome success');
assert.equal(dualOutcome(false, true), 'Partial outcome success');
assert.equal(dualOutcome(false, false), 'Neither outcome target met');
assert.equal(dualOutcome(null, true), 'Evaluation incomplete');
assert.ok(serviceReport(example).includes('40 percentage points'));
assert.ok(serviceReport(initialService(false)).includes('No post-action result.'));
assert.equal(serviceCsv(example).split('\n').length, 41);
assert.ok(serviceCsv(confirmServiceTicket(example, 'SC-R-017', { ...confirmation, reference: '=2+2' })).includes('"\'=2+2"'), 'Editable CSV references must not become spreadsheet formulas');
assert.ok(!serviceCsv(initialService(false)).includes('ANSWER-SC'), 'Do not export follow-up evidence before service execution');
const publicDraft = initialImpact(false); publicDraft.goal = 'An existing public-narrative draft';
assert.deepEqual(parseImpact(JSON.stringify(publicDraft), false), publicDraft, 'Service integration preserves v7 public draft format');
assert.equal(evaluateImpact(initialImpact()).adjusted, -20, 'Service edits must not mutate the public sample');
assert.equal(serviceTickets(example).length, 40);
function confirmedCount(review: typeof example) { return Object.keys(review.confirmations).length; }
console.log('Passed: fixed complaint cohorts, closure vs verification, reopened/cutoff safeguards, independent comparisons, confirmation eligibility, persistence, sign-off invalidation, dual outcomes and v7 draft compatibility.');
