import assert from 'node:assert/strict';
import { changeImpactEvidence, evaluateImpact, impactRecords, impactReport, initialImpact, lockImpactPlan, parseImpact, recordImpactExecution, signImpactReview } from '../src/investigation/impact-model';

const example = initialImpact();
const result = evaluateImpact(example);
assert.equal(result.records.length, 800);
assert.equal(new Set(result.records.map(r => r.id)).size, 800);
assert.deepEqual(result.responseBefore, { count: 200, assertions: 120, rate: 60 });
assert.deepEqual(result.responseAfter, { count: 200, assertions: 60, rate: 30 });
assert.deepEqual(result.comparisonBefore, { count: 200, assertions: 100, rate: 50 });
assert.deepEqual(result.comparisonAfter, { count: 200, assertions: 80, rate: 40 });
assert.equal(result.observed, -30);
assert.equal(result.adjusted, -20);
assert.equal(result.expected, 50);
assert.equal(result.targetMet, true);

const worse = evaluateImpact({ ...example, sampleMode: 'worse' });
assert.equal(worse.responseAfter.rate, 65);
assert.equal(worse.observed, 5);
assert.equal(worse.adjusted, 15);
assert.equal(worse.targetMet, false);
const missing = evaluateImpact({ ...example, sampleMode: 'missing' });
assert.equal(missing.comparisonAfter.rate, null, 'Missing data must not become a zero assertion rate');
assert.equal(missing.adjusted, null);
assert.equal(missing.targetMet, null);
assert.equal(missing.evidence, 'Insufficient data');
assert.equal(missing.records.length, 600);
for (const key of ['trends', 'spillover', 'collection', 'events'] as const) {
  const unresolved = evaluateImpact({ ...example, checks: { ...example.checks, [key]: false } });
  assert.equal(unresolved.adjusted, null, `Withhold estimate when ${key} is unresolved`);
  assert.equal(unresolved.targetMet, true, 'Observed target and attribution must remain separate');
}
let draft = initialImpact(false);
const execution = { officer: 'Demo officer', channel: 'Public notice', proof: 'receipt-001', wording: 'Temporary closure; schedule attached.', recordedAt: '2026-10-23T01:00:00Z' };
assert.equal(evaluateImpact(draft).adjusted, null);
assert.equal(evaluateImpact(draft).observed, null);
assert.equal(evaluateImpact(draft).targetMet, null);
assert.equal(recordImpactExecution(draft, execution), draft, 'Execution requires a locked plan');
assert.equal(lockImpactPlan({ ...draft, target: NaN }, 'now').lockedAt, null);
assert.equal(lockImpactPlan({ ...draft, target: 101 }, 'now').lockedAt, null);
draft = lockImpactPlan(draft, '2026-10-23T00:00:00Z');
assert.ok(draft.lockedAt);
assert.equal(lockImpactPlan(draft, 'later'), draft, 'An existing plan cannot be relocked');
assert.equal(recordImpactExecution(draft, { ...execution, proof: '' }), draft);
draft = recordImpactExecution(draft, execution);
assert.ok(draft.execution);
assert.notEqual(draft.execution, execution, 'Preserve a snapshot of the actual action');
assert.equal(recordImpactExecution(draft, { ...execution, wording: 'Changed' }), draft, 'Do not overwrite execution');
assert.equal(evaluateImpact(draft).evidence, 'Observed change only');
const signoff = { reviewer: 'AR', decision: 'Collect more evidence', note: 'Comparison exposure needs further verification.', recordedAt: '2026-10-23T02:00:00Z' };
assert.equal(signImpactReview(initialImpact(false), signoff).signoff, null);
assert.equal(signImpactReview(draft, { ...signoff, note: '' }).signoff, null);
const reviewed = signImpactReview(draft, signoff);
assert.ok(reviewed.signoff);
assert.equal(changeImpactEvidence(reviewed, { sampleMode: 'missing' }, 'later').signoff, null, 'Evidence changes invalidate prior sign-off');
assert.equal(changeImpactEvidence(reviewed, { checks: { ...reviewed.checks, trends: true } }, 'later').signoff, null);
assert.deepEqual(parseImpact(JSON.stringify(reviewed), false), reviewed);
for (const invalid of [null, 'not json', '{}', JSON.stringify({ ...draft, target: -1 }), JSON.stringify({ ...draft, checks: {} }), JSON.stringify({ ...draft, execution: {} }), JSON.stringify({ ...draft, signoff: {} }), JSON.stringify({ ...draft, lockedAt: null }), JSON.stringify({ ...draft, history: [{ at: 17, text: '' }] }), JSON.stringify({ ...draft, sampleMode: 'invented' })]) assert.deepEqual(parseImpact(invalid, false), initialImpact(false));
const report = impactReport(example);
assert.ok(report.includes('-20.0 percentage points'));
assert.ok(report.includes('No statistical significance computed'));
assert.ok(impactReport(initialImpact(false)).includes('Not recorded; no post-action conclusion.'));
assert.equal(impactRecords('complete').length, 800, 'Evaluation must not mutate its source fixture');
console.log('Passed: exact denominators and difference of changes; adverse and missing outcomes; execution and plan gates; independent target/attribution statuses; sign-off invalidation; draft validation and exports.');
